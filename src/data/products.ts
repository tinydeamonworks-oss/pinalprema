// Sivakasi Factory Standard Pricing:
// MRP is set such that our direct showroom price reflects flat 20% OFF (20% discount on MRP)
// Formula: MRP = Price / (1 - 0.20) = Price / 0.80 = Price * 1.25 (rounded to nearest 10)
// This gives exactly 20% OFF festival discount for all crackers!
export const PRODUCTS: Product[] = RAW_PRODUCTS.map((p) => {
  const roundTo = p.price < 100 ? 5 : 10;
  let computedMrp = Math.round((p.price / 0.8) / roundTo) * roundTo;

  if (computedMrp <= p.price) {
    computedMrp = p.price + roundTo;
  }

  return {
    ...p,
    mrp: computedMrp,
    discountPercent: 20, // Flat 20% OFF festive discount
  };
});
